# ==============================================================================
# config/initializers/good_job.rb（G-4: RestModeExpiryJob の cron 追加）
# ==============================================================================
#
# 【G-4 での変更内容】
#   ⑥ お休みモード期限切れ自動解除ジョブを追加
#      毎日 JST AM4:10 に実行し、rest_mode_until が過ぎたレコードをクリアする。
# ==============================================================================

Rails.application.configure do
  # ============================================================================
  # 同時実行数（スレッド数）の設定
  # ============================================================================
  config.good_job.max_threads = 3

  # ============================================================================
  # ポーリング間隔の設定
  # ============================================================================
  config.good_job.poll_interval = 30

  # ============================================================================
  # cron（定期ジョブ）を動かすかどうかの設定
  # ============================================================================
  #
  # 【なぜ明示的に有効にするのか】
  #   GoodJob の enable_cron は初期値が false（無効）。
  #   下の config.good_job.cron に予定を書いただけでは、ジョブは一度も登録されない。
  #   実際に本番 DB を調べると、cron のジョブの記録が 1 件も無かった。
  #
  # 【なぜ本番だけ有効にするのか】
  #   開発環境でも execution_mode が :async なので、有効にすると
  #   ローカルで docker compose を起動している時間帯に、週次レポートメールなどが動いてしまう。
  #   動作確認が必要なときは、GoodJob の管理画面（/good_job → Cron）から手動で実行できる。
  #
  # 【Render の無料プランで止まっている時間帯について】
  #   Render の無料プランは 15 分アクセスが無いとアプリを止めるため、
  #   予定の時刻にアプリが起きている必要がある。
  #   外部の cron-job.org が、予定の少し前に /up へアクセスしてアプリを起こしている（下の cron の設定を参照）。
  #
  # 【Puma のワーカーが 2 つあっても二重に実行されない理由】
  #   cron のジョブは「cron の名前（cron_key）＋予定時刻（cron_at）」で一意になるよう
  #   DB に制約があり、2 つ目の登録は GoodJob が自動で取りやめる。
  config.good_job.enable_cron = Rails.env.production?

  # ============================================================================
  # LISTEN/NOTIFY（新しいジョブの通知）を使うかどうかの設定
  # ============================================================================
  #
  # 【なぜ無効にするのか】
  #   本番の DATABASE_URL は Neon の pooler（PgBouncer の transaction モード）経由。
  #   transaction モードでは接続がトランザクションごとに使い回されるため、
  #   LISTEN の登録が外れ、Render のログに
  #   「[GoodJob] Notifier errored: … PQsocket() can't get socket descriptor」が出ていた（7日間で10件）。
  #
  # 【無効にしてもジョブが遅れない理由】
  #   HabitFlow は execution_mode :async で、ジョブの登録と実行が同じ Puma のプロセスの中で行われる。
  #   同じプロセスで登録したジョブは、通知を待たずにそのプロセス自身がすぐ実行する。
  #   別のプロセスで登録されたジョブも、上の poll_interval（30 秒）ごとの確認で拾われる。
  config.good_job.enable_listen_notify = false

  # ============================================================================
  # 完了済みジョブの保持期間の設定
  # ============================================================================
  config.good_job.cleanup_preserved_jobs_before_seconds_ago = 86_400

  # ============================================================================
  # Issue #I-5: GoodJob スレッド内システムエラーの Sentry 連携
  # ============================================================================
  #
  # 【on_thread_error フックとは何か】
  #   通常のジョブ失敗（perform 内の raise）は sentry-rails の ActiveJob 連携が
  #   ジョブ名付きで自動報告する。一方、GoodJob の実行スレッドやスケジューラ内部
  #   （＝ジョブの外側）で起きた致命的エラーは、そのままでは Sentry に届かない。
  #   このフックで拾って通知する。
  #
  # 【なぜ先に Rails.logger.error でログを残すのか（重要な保険）】
  #   on_thread_error を上書きすると GoodJob 既定のエラーログ出力も置き換わる。
  #   Sentry 通知だけにすると、Sentry 無効な開発環境（DSN未設定）では
  #   スレッドエラーが「無言で消える」危険がある。まずログに残して全環境で
  #   可視性を保証し、その上で本番だけ Sentry に送る。
  #
  # 【with_scope で情報を付与する理由（追跡性の向上）】
  #   ・set_tags(source: ...) … Sentry 画面で「GoodJob基盤のエラー」だけを絞り込める。
  #   ・set_context("good_job", thread:) … perform 外のエラーはジョブ名が特定できないため、
  #     せめてどのスレッドで落ちたかの手掛かりを残す。
  #     Thread.current.name は名前未設定スレッドでは nil を返すため "unknown" で補い、
  #     Sentry 画面に thread=null が並ぶのを防ぐ。
  #
  # 【Sentry.initialized? でガードする理由】
  #   本番のみ初期化されるため、dev/test では送信されない（no-op）。
  config.good_job.on_thread_error = ->(exception) do
    Rails.logger.error("[GoodJob] thread error: #{exception.class} - #{exception.message}")

    if Sentry.initialized?
      Sentry.with_scope do |scope|
        scope.set_tags(source: "good_job.on_thread_error")
        scope.set_context("good_job", { thread: Thread.current.name || "unknown" })
        Sentry.capture_exception(exception)
      end
    end
  end

  # ============================================================================
  # cron（定期ジョブ）の設定
  # ============================================================================
  #
  # 【時刻の書き方：末尾に Asia/Tokyo を付けて、日本時間で書く】
  #   cron 式は、GoodJob が使っているライブラリ Fugit が読む。
  #   式の末尾にタイムゾーン名を付けると、その地域の時刻として扱われる。
  #     例："5 4 * * * Asia/Tokyo" ＝ 日本時間の毎日 4:05
  #   以前は「UTC で書く」つもりで "5 19 * * *"（UTC 19:05 ＝ JST 4:05）のように書いていたが、
  #   config/application.rb の config.time_zone = "Tokyo" により、式がそのまま日本時間として扱われ、
  #   JST 19:05 に動く状態だった
  #   （2026-11-21 に、"0 15 * * *" のジョブが JST 15:00 に実行された記録で判明）。
  #   タイムゾーンを式に書いておけば、サーバーやアプリのタイムゾーンの設定に左右されない。
  #
  # 【毎日 4 時台の順番】
  #   4:05 ストリーク計算 → 4:10 お休みモード解除 → 4:15 AI プロファイル更新（月曜）
  #   ストリークを計算し終えてからお休みモードを解除し、
  #   最新の習慣データでプロファイルを更新するため、この順番にしている。
  #
  # 【Render の無料プランで止まっている時間帯について】
  #   外部の無料サービス cron-job.org が、予定の少し前に /up へアクセスしてアプリを起こしている
  #   （日本時間で毎日 23:55、毎日 4:00 と 4:10、月曜 8:55）。
  #   時刻を変えたときは、cron-job.org の設定も合わせて変える。
  #
  # 【テスト】
  #   test/integration/good_job_cron_config_test.rb が、各 cron が決めた日本時間に動くかを確かめる。
  config.good_job.cron = {
    # --------------------------------------------------------------------------
    # ① ストリーク日次計算ジョブ（毎日 JST 4:05）
    # --------------------------------------------------------------------------
    streak_daily_calculation: {
      cron: "5 4 * * * Asia/Tokyo",
      class: "StreakCalculationJob",
      description: "毎日 JST AM4:05 にストリーク（連続達成日数）を計算・更新する"
    },

    # --------------------------------------------------------------------------
    # ② 日次通知カウントリセットジョブ（毎日 JST 0:05）
    # --------------------------------------------------------------------------
    daily_notification_count_reset: {
      cron: "5 0 * * * Asia/Tokyo",
      class: "DailyNotificationCountResetJob",
      description: "毎日 JST 00:05 に daily_notification_count を 0 にリセットする"
    },

    # --------------------------------------------------------------------------
    # ③ 月次 AI 使用回数リセットジョブ（毎日 JST 0:00 に動き、1 日のときだけリセットする）
    # --------------------------------------------------------------------------
    monthly_ai_count_reset: {
      cron: "0 0 * * * Asia/Tokyo",
      class: "MonthlyAiCountResetJob",
      description: "毎日 JST 00:00 に実行。月初（1日）のみ ai_analysis_count を 0 にリセットする"
    },

    # --------------------------------------------------------------------------
    # ④ 完了済みジョブのクリーンアップ → cron からは削除した
    # --------------------------------------------------------------------------
    # 以前は class: "GoodJob::CleanupJobsJob" を毎日 JST 03:00 に登録していたが、
    # GoodJob 4.19.2 にこのクラスは無く、実行すると NameError になる
    # （enable_cron が無効だったため、これまでエラーが表に出ていなかった）。
    # GoodJob は、ジョブを実行するスケジューラが一定間隔（cleanup_interval_seconds）ごとに、
    # 上の cleanup_preserved_jobs_before_seconds_ago（24 時間）より古い完了済みジョブを
    # 自動で削除する。そのため、cron で片付けのジョブを登録する必要は無い。

    # --------------------------------------------------------------------------
    # ⑤ 週次レポートメール送信ジョブ（毎週月曜 JST 9:00、G-2 追加）
    # --------------------------------------------------------------------------
    weekly_report_mail: {
      cron:        "0 9 * * 1 Asia/Tokyo",
      class:       "WeeklyReportJob",
      description: "毎週月曜日 JST AM9:00 に週次レポートメールを送信する"
    },

    # --------------------------------------------------------------------------
    # ⑥ お休みモード期限切れ自動解除ジョブ（毎日 JST 4:10、G-4 追加）
    # --------------------------------------------------------------------------
    # ① のストリーク計算（4:05）の直後に実行することで、
    # 「お休みモード終了日当日」のストリーク計算が終わってから、お休みモードを解除できる。
    rest_mode_expiry: {
      cron:        "10 4 * * * Asia/Tokyo",
      class:       "RestModeExpiryJob",
      description: "毎日 JST AM4:10 に rest_mode_until が過ぎた設定を自動解除する"
    },

    # --------------------------------------------------------------------------
    # ⑦ パーソナライズAIプロファイル週次更新ジョブ（毎週月曜 JST 4:15、H-8 追加）
    # --------------------------------------------------------------------------
    # 週次レポートメール（月曜 9:00）より前に実行し、メールの送信前にプロファイルを最新にする。
    update_ai_profiles: {
      cron:        "15 4 * * 1 Asia/Tokyo",
      class:       "UpdateAiProfileJob",
      description: "毎週月曜日 JST AM4:15 に全ユーザーのパーソナライズAIプロファイルを更新する"
    }
  }
end
