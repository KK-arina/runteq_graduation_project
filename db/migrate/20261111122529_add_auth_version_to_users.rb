# users に auth_version（ログインの世代番号）を追加する
# ==============================================================================
#
# 【なぜ必要なのか】
#   Rails のセッションは暗号化された Cookie に入っているため、
#   サーバー側から「この人のセッションを消す」ことができない。
#   スマホを紛失して「すべての端末を解除」しても、紛失したスマホのブラウザに
#   セッションが残っていると、ログインしたままになってしまう。
#
#   そこで「ログインの世代番号」を users に持たせ、ログイン時にセッションにも記録する。
#   すべての端末の解除・パスワードリセット・退会のときにこの番号を1つ増やすと、
#   古い番号を持ったセッションは「古い世代」と判定されて自動的にログアウトになる。
#
# 【DB への負担が増えない理由】
#   current_user を取得するときに users の1行は毎回読み込んでいるので、
#   その中の auth_version とセッションの値を比べるだけで済む（追加の SQL はゼロ）。
#
# 【default: 0 にする理由】
#   すでにログインしている人のセッションには auth_version が入っていない（nil）。
#   比較するときに nil.to_i（= 0）として扱うので、DB の初期値も 0 にしておけば、
#   デプロイした瞬間に全員が強制ログアウトされることはない。
#
# 【大きな表でも安全な理由】
#   PostgreSQL 11 以降は「default 付きのカラム追加」でも全行を書き換えないため、
#   一瞬で終わる（本番の Neon は PostgreSQL 16）。
# ==============================================================================
class AddAuthVersionToUsers < ActiveRecord::Migration[8.1]
  def change
    # null: false → 値が必ず入っている状態にして、比較処理を単純にする
    add_column :users, :auth_version, :integer, null: false, default: 0
  end
end