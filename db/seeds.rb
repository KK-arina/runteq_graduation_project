# ==============================================================================
# db/seeds.rb（#I-3: 役割分割版・司令塔）
# ==============================================================================
#
# 【このファイルの役割】
#   db:seed で投入するデータを「役割ごとの別ファイル」に振り分ける司令塔です。
#   ここには具体的な投入処理を書かず、どのファイルをどの環境で読み込むかだけを
#   決めます。こうすることで「本番に必要なデータ」と「開発用のデモデータ」が
#   はっきり分離され、事故が起きにくくなります。
#
#   ▼ db/seeds/habit_templates.rb … 習慣テンプレート（マスタデータ）
#       全ユーザー共通の参照データ。オンボーディングで表示する。
#       冪等（何度実行しても同じ）かつ非破壊（既存データを消さない）なので、
#       本番・開発・テストのどの環境でも安全に読み込む。
#
#   ▼ db/seeds/demo_data.rb … デモユーザー・習慣・記録・振り返り
#       開発時の見た目確認や講師レビュー用のサンプルデータ。
#       冒頭で全データを削除する破壊的な処理を含むため、
#       ★開発環境（development）でのみ読み込む。★
#
# 【実行コマンド】
#   docker compose exec web bin/rails db:seed
#
# 【なぜ load を使うのか】
#   require は「1度読み込んだファイルを2度目は読み込まない」動きをするため、
#   何度も実行される可能性がある seed には向かない。
#   load は「呼ばれるたびに必ず実行する」ため、seed の分割読み込みに適している。
# ==============================================================================

# ------------------------------------------------------------------------------
# Part A: マスタデータ（習慣テンプレート）— 全環境で常に投入
# ------------------------------------------------------------------------------
# 本番でも必要なデータなので、環境に関係なく必ず読み込む。
# 中身は冪等・非破壊なので、本番で何度実行しても既存データは消えない。
load Rails.root.join("db/seeds/habit_templates.rb").to_s

# ------------------------------------------------------------------------------
# Part B: デモデータ — 開発環境（development）でのみ投入
# ------------------------------------------------------------------------------
# demo_data.rb は全データ削除を含む破壊的な処理なので、
# development のときだけ読み込む。本番・テストでは読み込まない
# （＝本番の実行経路には破壊的コードが一切登場しない）。
if Rails.env.development?
  load Rails.root.join("db/seeds/demo_data.rb").to_s
else
  puts "ℹ️  #{Rails.env} 環境のため、デモデータ（demo_data.rb）はスキップしました。"
  puts "    テンプレートのみ投入済みです（既存データは削除していません）。"
end
